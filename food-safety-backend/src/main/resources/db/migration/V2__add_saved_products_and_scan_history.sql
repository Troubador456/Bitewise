CREATE TABLE saved_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    barcode VARCHAR(14) NOT NULL,
    ingredients TEXT,
    saved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_saved_products_user_barcode UNIQUE (user_id, barcode),
    CONSTRAINT fk_saved_products_user FOREIGN KEY (user_id)
        REFERENCES auth_users (id) ON DELETE CASCADE
);

CREATE INDEX ix_saved_products_user_saved_at ON saved_products (user_id, saved_at DESC);

CREATE TABLE scan_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    barcode VARCHAR(14),
    product_name VARCHAR(255) NOT NULL,
    safety_result VARCHAR(20) NOT NULL
        CHECK (safety_result IN ('SAFE', 'WARNING', 'UNSAFE')),
    scanned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_scan_history_user FOREIGN KEY (user_id)
        REFERENCES auth_users (id) ON DELETE CASCADE
);

CREATE INDEX ix_scan_history_user_scanned_at ON scan_history (user_id, scanned_at DESC);
